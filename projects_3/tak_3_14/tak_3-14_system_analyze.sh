#!/bin/bash
echo "Анализ дискового пространства"
echo "Файловая система  Заполнение"
echo "----------------------------"

df -h | awk 'NR>1 {
    # Вывод названия и процента
    printf "%-16s %s/n", $1, $5;
    # Проверка на превышение 90% (сравниваем)
    gsub(/%/, "", $5);
    if ($5 > 90) {
        print " ПРЕДУПРЕЖДЕНИЕ: раздел заполнен на %s%%!\n ", $1, $5;
    }
}'
